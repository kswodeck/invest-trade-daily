        fmt_price(entry.get("ideal"), unit),
        f"{idea['distance_to_entry_pct']:+.2f}%" if idea.get("distance_to_entry_pct") is not None else "",
        fmt_zone(entry, unit),
        fmt_price(exit_.get("target"), unit),
