#!/usr/bin/env python3
"""Publish a daily report to Google Sheets and grade prior calls.

    python scripts/publish_sheets.py reports/2026-08-12/report.json
    python scripts/publish_sheets.py reports/2026-08-12/report.json --dry-run

Writes three things to the spreadsheet named by GOOGLE_SHEET_ID:

  Today        this morning's ranked ideas, overwritten each run
  <date>       an immutable dated archive of the same content
  Performance  running scorecard of every idea ever published

Requires GCP_SERVICE_ACCOUNT_JSON (the whole key file, as a string) and
GOOGLE_SHEET_ID. The Sheet must be shared with the service account's
client_email as an Editor — that is the most common setup failure.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
STATE_PATH = REPO / "state" / "open_positions.json"
SCHEMA_PATH = REPO / "scripts" / "report_schema.json"

sys.path.insert(0, str(REPO / "scripts"))

HEADERS = [
    "#", "Instrument", "Symbol", "Class", "Venue", "Direction", "Horizon",
    "Conv", "Last", "Entry", "Entry Zone", "Target", "Target 2", "Stop",
    "R:R", "Size %", "Catalyst", "When (ET)", "Action / Timing", "Thesis",
    "Key Risk", "Sources",
]

PERF_HEADERS = [
    "Opened", "Instrument", "Symbol", "Venue", "Direction", "Horizon",
    "Entry", "Target", "Stop", "Status", "Last Price", "% vs Entry",
    "Days Open", "Closed", "Note",
]

DISCLAIMER = (
    "Automated research, not investment advice. Generated by an AI model from public data; "
    "it can be confidently wrong and prices may be stale. Futures are leveraged and can lose "
    "more than you deposit. You are responsible for every trade you place."
)

# Google Sheets colors are 0..1 floats, not 0..255 ints.
INK = {"red": 0.13, "green": 0.13, "blue": 0.15}
HEADER_BG = {"red": 0.16, "green": 0.19, "blue": 0.27}
WHITE = {"red": 1.0, "green": 1.0, "blue": 1.0}
GREEN = {"red": 0.85, "green": 0.94, "blue": 0.86}
RED = {"red": 0.98, "green": 0.87, "blue": 0.87}
AMBER = {"red": 1.0, "green": 0.95, "blue": 0.80}
GREY = {"red": 0.95, "green": 0.95, "blue": 0.96}

BULLISH = {"buy", "long", "yes"}
BEARISH = {"sell", "sell_short", "short", "no"}


