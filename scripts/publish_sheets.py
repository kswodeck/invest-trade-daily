def validate(report: dict) -> None:
    try:
        import jsonschema
    except ImportError:
        print("  note: jsonschema not installed, skipping validation", file=sys.stderr)
        return
    jsonschema.validate(report, json.loads(SCHEMA_PATH.read_text()))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("report", type=Path)
    ap.add_argument("--dry-run", action="store_true", help="grade and render, but do not touch the Sheet")
    ap.add_argument("--skip-performance", action="store_true")
    args = ap.parse_args(argv)

    report = json.loads(args.report.read_text())
    validate(report)
    report_date = date.fromisoformat(report["date"])

    ideas = sorted(report.get("recommendations", []), key=lambda i: i.get("rank", 99))
    today_values, header_row = build_today_values(report)

    # Grade prior calls before appending today's, so a repeat idea does not
    # get graded against itself on the same run.
    positions = load_state()
    if not args.skip_performance:
        print(f"Grading {len([p for p in positions if p.get('status') == 'open'])} open positions...")
        positions = [grade_position(p, report_date) for p in positions]

    existing = {(p.get("opened"), p.get("symbol"), p.get("direction")) for p in positions}
    new = [p for p in positions_from_report(report) if
           (p["opened"], p["symbol"], p["direction"]) not in existing]
    positions.extend(new)
    print(f"Added {len(new)} new positions; {len(positions)} tracked in total.")

    perf_values = [
        ["PERFORMANCE TRACKER"],
        summarize(positions),
        [""],
        PERF_HEADERS,
    ]
    perf_values.extend(
        perf_row(p) for p in sorted(positions, key=lambda p: p.get("opened", ""), reverse=True)
    )

    if args.dry_run:
        print("\n--- DRY RUN: Today tab ---")
        for row in today_values[:header_row + len(ideas) + 2]:
            print("  " + " | ".join(str(c)[:28] for c in row))
        print("\n--- DRY RUN: Performance tab ---")
        for row in perf_values[:12]:
            print("  " + " | ".join(str(c)[:22] for c in row))
        save_state(positions)
        print(f"\nState written to {STATE_PATH.relative_to(REPO)}. Sheet not touched.")
        return 0

    # Persist before touching Sheets. Grading and capture are already done and do
    # not depend on the Sheet, so a Google outage should not also cost us the
    # position tracking — that would silently orphan a day of picks.
    save_state(positions)
    print(f"State saved to {STATE_PATH.relative_to(REPO)} ({len(positions)} positions).")

    spreadsheet, client_email = open_spreadsheet()
    print(f"Opened spreadsheet as {client_email}")

    write_tab(spreadsheet, "Today", today_values, header_row, ideas)
    print("  wrote 'Today'")

    write_tab(spreadsheet, report["date"], today_values, header_row, ideas)
    print(f"  wrote archive '{report['date']}'")

    write_tab(spreadsheet, "Performance", perf_values, 4, [])
    print("  wrote 'Performance'")

    # Keep Today and Performance at the front, archives behind them.
    try:
        order = ["Today", "Performance"]
        spreadsheet.reorder_worksheets(
            [spreadsheet.worksheet(t) for t in order]
            + [ws for ws in spreadsheet.worksheets() if ws.title not in order]
        )
    except Exception as exc:  # noqa: BLE001
        print(f"  warning: could not reorder tabs: {exc}", file=sys.stderr)

    print(f"Done. {len(ideas)} ideas published for {report['date']}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
