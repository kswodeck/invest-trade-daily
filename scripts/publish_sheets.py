def _col(header: str) -> str:
    """Spreadsheet column letter for a Performance header, by name.

    Looked up rather than hardcoded so the formulas below cannot drift out of
    sync with the table when a column is inserted.
    """
    i = PERF_HEADERS.index(header)
    letter = ""
    while True:
        letter = chr(ord("A") + i % 26) + letter
        i = i // 26 - 1
        if i < 0:
            return letter


