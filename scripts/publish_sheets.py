# Google's Sheets API returns these intermittently under load. They say nothing
# about credentials and clear on their own, so they are worth retrying rather
# than failing a morning over.
TRANSIENT_STATUS = {429, 500, 502, 503, 504}
AUTH_STATUS = {401, 403, 404}


def _status_code(exc: Exception) -> int | None:
    """Pull an HTTP status out of a gspread APIError, however it is carried."""
    code = getattr(getattr(exc, "response", None), "status_code", None)
    if code:
        return int(code)
    match = re.search(r"\[(\d{3})\]", str(exc))
    return int(match.group(1)) if match else None


def with_retry(fn: Any, what: str, attempts: int = 5) -> Any:
    """Retry `fn` through transient Google errors with exponential backoff."""
    delay = 2.0
    for attempt in range(1, attempts + 1):
        try:
            return fn()
        except Exception as exc:  # noqa: BLE001
            code = _status_code(exc)
            if code not in TRANSIENT_STATUS or attempt == attempts:
                raise
            print(f"  {what}: HTTP {code}, retrying in {delay:.0f}s "
                  f"(attempt {attempt}/{attempts})", file=sys.stderr)
            time.sleep(delay)
            delay *= 2
    raise RuntimeError("unreachable")


def open_spreadsheet():
    import gspread
    from google.oauth2.service_account import Credentials

    raw = os.environ.get("GCP_SERVICE_ACCOUNT_JSON", "").strip()
    sheet_id = os.environ.get("GOOGLE_SHEET_ID", "").strip()
    if not raw:
        raise SystemExit("GCP_SERVICE_ACCOUNT_JSON is not set")
    if not sheet_id:
        raise SystemExit("GOOGLE_SHEET_ID is not set")
    try:
        info = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"GCP_SERVICE_ACCOUNT_JSON is not valid JSON: {exc}") from exc

    creds = Credentials.from_service_account_info(
        info, scopes=["https://www.googleapis.com/auth/spreadsheets"]
    )
    client = gspread.authorize(creds)
    email = info.get("client_email")
    try:
        sheet = with_retry(lambda: client.open_by_key(sheet_id), "opening the spreadsheet")
        return sheet, email
    except Exception as exc:  # noqa: BLE001
        code = _status_code(exc)
        if code in AUTH_STATUS:
            raise SystemExit(
                f"Could not open sheet {sheet_id}: {exc}\n"
                f"HTTP {code} means the service account cannot reach this Sheet. "
                f"Share it with {email} as an Editor."
            ) from exc
        raise SystemExit(
            f"Could not open sheet {sheet_id} after retries: {exc}\n"
            f"HTTP {code} is a transient Google API failure, not a permissions problem — "
            f"the credentials and sharing are almost certainly fine. Re-run the workflow."
        ) from exc


def get_or_create(spreadsheet, title: str, rows: int, cols: int):
    """Fetch or create a tab, sized to hold `rows` x `cols`.

    Clearing a worksheet does not resize its grid, so a reused tab keeps
    whatever dimensions it was created with. Performance grows by a few rows
    every day and would eventually exceed them, failing the write with
    "exceeds grid limits" — so grow the grid explicitly when needed.
    """
    rows, cols = max(rows, 50), max(cols, 26)
    try:
        ws = spreadsheet.worksheet(title)
    except Exception:  # noqa: BLE001 - gspread raises WorksheetNotFound
        return spreadsheet.add_worksheet(title=title, rows=rows, cols=cols)

    ws.clear()
    if ws.row_count < rows or ws.col_count < cols:
        ws.resize(rows=max(rows, ws.row_count), cols=max(cols, ws.col_count))
    return ws


def style_grid(ws, header_row: int, n_cols: int, n_rows: int, spec: dict[str, Any]) -> None:
    """Header banding, direction tinting, and column widths in one batch."""
    sid = ws.id
    reqs: list[dict] = [
        {  # title
            "repeatCell": {
                "range": {"sheetId": sid, "startRowIndex": 0, "endRowIndex": 1},
                "cell": {"userEnteredFormat": {
                    "textFormat": {"bold": True, "fontSize": 14, "foregroundColor": INK}}},
                "fields": "userEnteredFormat.textFormat",
            }
        },
        {  # header band
            "repeatCell": {
                "range": {
                    "sheetId": sid,
                    "startRowIndex": header_row - 1, "endRowIndex": header_row,
                    "startColumnIndex": 0, "endColumnIndex": n_cols,
                },
                "cell": {"userEnteredFormat": {
                    "backgroundColor": HEADER_BG,
                    "textFormat": {"bold": True, "foregroundColor": WHITE, "fontSize": 10},
                    "verticalAlignment": "MIDDLE",
                    "horizontalAlignment": "CENTER",
                }},
                "fields": "userEnteredFormat(backgroundColor,textFormat,verticalAlignment,horizontalAlignment)",
            }
        },
        {"updateSheetProperties": {
            "properties": {"sheetId": sid, "gridProperties": {"frozenRowCount": header_row}},
            "fields": "gridProperties.frozenRowCount",
        }},
        {"updateDimensionProperties": {  # wrap the prose columns
            "range": {"sheetId": sid, "dimension": "COLUMNS", "startIndex": COL_PROSE_START + 2, "endIndex": COL_PROSE_END},
            "properties": {"pixelSize": 320},
            "fields": "pixelSize",
        }},
        {"updateDimensionProperties": {
            "range": {"sheetId": sid, "dimension": "COLUMNS", "startIndex": 1, "endIndex": 2},
            "properties": {"pixelSize": 180},
            "fields": "pixelSize",
        }},
        {"repeatCell": {
            "range": {"sheetId": sid, "startRowIndex": header_row, "endRowIndex": n_rows,
                      "startColumnIndex": COL_PROSE_START, "endColumnIndex": COL_PROSE_END},
            "cell": {"userEnteredFormat": {"wrapStrategy": "WRAP", "verticalAlignment": "TOP"}},
            "fields": "userEnteredFormat(wrapStrategy,verticalAlignment)",
        }},
    ]

    # Section banners: dark bar across the width so the eye finds them.
    for row in spec.get("sections", []):
        reqs.append({
            "repeatCell": {
                "range": {"sheetId": sid, "startRowIndex": row, "endRowIndex": row + 1,
                          "startColumnIndex": 0, "endColumnIndex": n_cols},
                "cell": {"userEnteredFormat": {
                    "backgroundColor": HEADER_BG,
                    "textFormat": {"bold": True, "foregroundColor": WHITE, "fontSize": 11},
                }},
                "fields": "userEnteredFormat(backgroundColor,textFormat)",
            }
        })

    # Tint the direction cell by side so the sheet is readable at a glance.
    for row, idea in spec.get("ideas", []):
        d = idea.get("direction", "")
        bg = GREEN if d in BULLISH else RED if d in BEARISH else GREY
        reqs.append({
            "repeatCell": {
                "range": {"sheetId": sid, "startRowIndex": row, "endRowIndex": row + 1,
                          "startColumnIndex": COL_DIRECTION, "endColumnIndex": COL_DIRECTION + 1},
                "cell": {"userEnteredFormat": {
                    "backgroundColor": bg,
                    "textFormat": {"bold": True},
                    "horizontalAlignment": "CENTER",
                }},
                "fields": "userEnteredFormat(backgroundColor,textFormat,horizontalAlignment)",
            }
        })
        conv = idea.get("conviction") or 0
        reqs.append({
            "repeatCell": {
                "range": {"sheetId": sid, "startRowIndex": row, "endRowIndex": row + 1,
                          "startColumnIndex": COL_CONVICTION, "endColumnIndex": COL_CONVICTION + 1},
                "cell": {"userEnteredFormat": {
                    "backgroundColor": GREEN if conv >= 5 else AMBER if conv >= 4 else GREY,
                    "horizontalAlignment": "CENTER",
                    "textFormat": {"bold": True},
                }},
                "fields": "userEnteredFormat(backgroundColor,horizontalAlignment,textFormat)",
            }
        })

    ws.spreadsheet.batch_update({"requests": reqs})


def style_performance(ws, formats: list[tuple[int, int, str]], block_start: int,
                      detail_first_row: int, total_rows: int) -> None:
    """Number formats for the cumulative block and the percent column."""
    sid = ws.id
    patterns = {
        "pct": {"type": "NUMBER", "pattern": PCT_FORMAT},
        "rate": {"type": "PERCENT", "pattern": "0.0%"},
    }
    reqs = [{
        "repeatCell": {
            "range": {"sheetId": sid, "startRowIndex": detail_first_row - 1,
                      "startColumnIndex": PERF_HEADERS.index("% vs Entry"),
                      "endColumnIndex": PERF_HEADERS.index("% vs Entry") + 1},
            "cell": {"userEnteredFormat": {"numberFormat": patterns["pct"]}},
            "fields": "userEnteredFormat.numberFormat",
        }
    }]
    for offset, col, kind in formats:
        row = block_start + offset
        if row >= total_rows:
            continue
        reqs.append({
            "repeatCell": {
                "range": {"sheetId": sid, "startRowIndex": row, "endRowIndex": row + 1,
                          "startColumnIndex": col, "endColumnIndex": col + 1},
                "cell": {"userEnteredFormat": {
                    "numberFormat": patterns[kind],
                    # The headline average is the row people read first.
                    "textFormat": {"bold": kind == "pct" and offset == HEADLINE_OFFSET},
                }},
                "fields": "userEnteredFormat(numberFormat,textFormat)",
            }
        })
    reqs.append({
        "repeatCell": {
            "range": {"sheetId": sid, "startRowIndex": block_start + 1,
                      "endRowIndex": block_start + 2},
            "cell": {"userEnteredFormat": {"textFormat": {"bold": True, "fontSize": 11}}},
            "fields": "userEnteredFormat.textFormat",
        }
    })
    ws.spreadsheet.batch_update({"requests": reqs})


def write_tab(spreadsheet, title: str, values: list[list[Any]], header_row: int,
              spec: dict[str, Any] | None = None, value_input_option: str = "RAW"):
    n_cols = max(len(r) for r in values)
    ws = with_retry(lambda: get_or_create(spreadsheet, title, len(values) + 10, n_cols + 2),
                    f"creating/clearing '{title}'")
    padded = [row + [""] * (n_cols - len(row)) for row in values]
    with_retry(lambda: ws.update(padded, "A1", value_input_option=value_input_option),
               f"writing '{title}'")
    if spec is not None:
        try:
            style_grid(ws, header_row, n_cols, len(values), spec)
        except Exception as exc:  # noqa: BLE001 - content matters more than styling
            print(f"  warning: formatting failed on '{title}': {exc}", file=sys.stderr)
    return ws


