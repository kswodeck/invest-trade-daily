def load_state() -> list[dict]:
    if STATE_PATH.exists():
        return json.loads(STATE_PATH.read_text() or "[]")
    return []


def save_state(positions: list[dict]) -> None:
    STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
    STATE_PATH.write_text(json.dumps(positions, indent=2) + "\n")


# Classes Yahoo can price, and therefore grade from daily bars. Event contracts
# have no free quote source and stay ungraded.
PRICEABLE = ("stock", "etf", "futures")


def _current_price(pos: dict) -> float | None:
    """Best-effort current price. None is an acceptable answer."""
    import market_data

    cls, symbol = pos.get("asset_class"), pos.get("symbol", "")
    try:
        if cls == "crypto":
            res = market_data.crypto([pos.get("coingecko_id") or symbol.lower()])
            if res.get("ok"):
                prices = list(res.get("prices", {}).values())
                return prices[0]["price"] if prices else None
            return None
        if cls in PRICEABLE:
            res = market_data.quote(symbol)
            return res.get("price") if res.get("ok") else None
    except Exception:  # noqa: BLE001 - grading must never break publishing
        return None
    return None


def grade_position(pos: dict, today: date) -> dict:
    """Update one open position in place-ish and return it."""
    if pos.get("status") not in (None, "open"):
        return pos

    opened = datetime.fromisoformat(pos["opened"]).date()
    pos["days_open"] = (today - opened).days

    entry = pos.get("entry")
    target = pos.get("target")
    stop = pos.get("stop")
    bullish = pos.get("direction") in BULLISH

    # Scan the bars since open so an intraday touch of the target or stop is
    # caught rather than only the closing price.
    if pos.get("asset_class") in PRICEABLE:
        try:
            import market_data

            hist = market_data.history(pos["symbol"], days=max(pos["days_open"] + 10, 20))
            if hist.get("ok"):
                for bar in hist.get("recent", []):
                    if bar["date"] <= opened.isoformat():
                        continue
                    hi, lo = bar["h"], bar["l"]
                    if target is not None and ((bullish and hi >= target) or (not bullish and lo <= target)):
                        pos.update(status="target_hit", closed=bar["date"], exit_price=target)
                        break
                    if stop is not None and ((bullish and lo <= stop) or (not bullish and hi >= stop)):
                        pos.update(status="stopped", closed=bar["date"], exit_price=stop)
                        break
        except Exception:  # noqa: BLE001
            pass

    last = pos.get("exit_price") or _current_price(pos)
    if last is not None:
        pos["last_price"] = last
        if entry:
            move = (last - entry) / entry * 100
            pos["pct_vs_entry"] = round(move if bullish else -move, 2)

    # Non-equity positions still resolve on the current print.
    if pos.get("status") in (None, "open") and last is not None:
        if target is not None and ((bullish and last >= target) or (not bullish and last <= target)):
            pos.update(status="target_hit", closed=today.isoformat(), exit_price=last)
        elif stop is not None and ((bullish and last <= stop) or (not bullish and last >= stop)):
            pos.update(status="stopped", closed=today.isoformat(), exit_price=last)

    # Time-box stale ideas so the tracker does not fill with zombies.
    # Long-term positions are meant to sit open for quarters, so expiring them
    # on a swing timetable would score every buy-and-hold thesis as a failure.
    max_days = {"intraday": 5, "swing": 45, "long_term": 730}.get(pos.get("horizon"), 45)
    if pos.get("status") in (None, "open") and pos["days_open"] > max_days:
        pos.update(status="expired", closed=today.isoformat())

    pos.setdefault("status", "open")
    return pos


def positions_from_report(report: dict) -> list[dict]:
    out = []
    for idea in report.get("recommendations", []):
        if (idea.get("catalyst") or {}).get("wait"):
            continue  # not entered today; nothing to track yet
        out.append({
            "opened": report["date"],
            "instrument": idea.get("instrument"),
            "symbol": idea.get("symbol"),
            "asset_class": idea.get("asset_class"),
            "venue": idea.get("venue"),
            "direction": idea.get("direction"),
            "horizon": idea.get("horizon"),
            "unit": idea.get("unit", "usd"),
            "entry": (idea.get("entry") or {}).get("ideal"),
            "target": (idea.get("exit") or {}).get("target"),
            "stop": idea.get("stop"),
            "conviction": idea.get("conviction"),
            "status": "open",
        })
    return out


def _price_note(pos: dict) -> str:
    if pos.get("asset_class") == "futures":
        # Yahoo quotes the continuous front-month, not the specific contract
        # month that was recommended, so the grade carries a basis error.
        base = "graded on continuous front-month; basis differs from the contract"
        return base if pos.get("last_price") is not None else f"{base}; price fetch failed"
    if pos.get("last_price") is not None:
        return ""
    if pos.get("asset_class") == "event":
        return "no free quote source for event contracts"
    return "price fetch failed this run"


def perf_row(pos: dict) -> list[Any]:
    unit = pos.get("unit", "usd")
    status = {
        "target_hit": "✓ TARGET", "stopped": "✗ STOPPED",
        "expired": "– EXPIRED", "open": "• OPEN",
    }.get(pos.get("status", "open"), pos.get("status", ""))
    pct = pos.get("pct_vs_entry")
    return [
        pos.get("opened", ""),
        pos.get("instrument", ""),
        pos.get("symbol", ""),
        (pos.get("venue") or "").replace("Robinhood ", "RH "),
        direction_label(pos.get("direction", "")),
        pos.get("horizon", ""),
        fmt_price(pos.get("entry"), unit),
        fmt_price(pos.get("target"), unit),
        fmt_price(pos.get("stop"), unit),
        status,
        fmt_price(pos.get("last_price"), unit),
        f"{pct:+.2f}%" if pct is not None else "",
        pos.get("days_open", ""),
        pos.get("closed", ""),
        pos.get("note") or _price_note(pos),
    ]


def summarize(positions: list[dict]) -> list[Any]:
    closed = [p for p in positions if p.get("status") in ("target_hit", "stopped", "expired")]
    wins = [p for p in closed if p.get("status") == "target_hit"]
    pcts = [p["pct_vs_entry"] for p in closed if p.get("pct_vs_entry") is not None]
    hit_rate = f"{len(wins) / len(closed) * 100:.0f}%" if closed else "—"
    avg = f"{sum(pcts) / len(pcts):+.2f}%" if pcts else "—"
    return [
        f"SCORECARD — {len(positions)} ideas tracked  ·  {len(closed)} closed  ·  "
        f"{len(wins)} hit target  ·  hit rate {hit_rate}  ·  avg move {avg}  ·  "
        f"{len([p for p in positions if p.get('status') == 'open'])} still open"
    ]


