def fmt_price(value: Any, unit: str = "usd") -> str:
    if value is None:
        return ""
    if unit == "cents":
        return f"{value:g}¢"
    if unit == "index_points":
        return f"{value:,.2f}"
    return f"${value:,.2f}" if value < 1000 else f"${value:,.0f}"


def fmt_zone(entry: dict, unit: str) -> str:
    lo, hi = entry.get("zone_low"), entry.get("zone_high")
    if lo is None or hi is None:
        return ""
    return f"{fmt_price(lo, unit)} – {fmt_price(hi, unit)}"


def direction_label(direction: str) -> str:
    return {
        "buy": "BUY", "sell": "SELL", "sell_short": "SHORT",
        "long": "LONG", "short": "SHORT", "yes": "YES", "no": "NO",
    }.get(direction, direction.upper())


def idea_row(idea: dict) -> list[Any]:
    unit = idea.get("unit", "usd")
    entry, exit_, cat = idea.get("entry", {}), idea.get("exit", {}), idea.get("catalyst", {})
    action = cat.get("action", "")
    if cat.get("wait"):
        action = f"⏸ WAIT — {action}"
    return [
        idea.get("rank", ""),
        idea.get("instrument", ""),
        idea.get("symbol", ""),
        idea.get("asset_class", "").upper(),
        idea.get("venue", "").replace("Robinhood ", "RH "),
        direction_label(idea.get("direction", "")),
        idea.get("horizon", ""),
        idea.get("conviction", ""),
        fmt_price(idea.get("last_price"), unit),
        fmt_price(entry.get("ideal"), unit),
        fmt_zone(entry, unit),
        fmt_price(exit_.get("target"), unit),
        fmt_price(exit_.get("target_2"), unit),
        fmt_price(idea.get("stop"), unit),
        f"{idea['risk_reward']:.1f}:1" if idea.get("risk_reward") else "",
        f"{idea['position_size_pct']:g}%" if idea.get("position_size_pct") else "",
        cat.get("event", ""),
        cat.get("datetime_et") or "",
        action,
        idea.get("thesis", ""),
        idea.get("key_risk", ""),
        "\n".join(idea.get("sources", [])[:4]),
    ]


def build_today_values(report: dict) -> tuple[list[list[Any]], int]:
    """Returns (rows, header_row_index_1based)."""
    ctx = report.get("market_context", {})
    levels = ctx.get("levels") or {}
    level_str = "  ·  ".join(f"{k.upper()} {v}" for k, v in levels.items() if v is not None)

    rows: list[list[Any]] = [
        [f"DAILY TRADE REPORT — {report.get('date', '')}"],
        [f"Generated {report.get('generated_at_et', '')}  ·  regime: {ctx.get('regime', 'unknown')}"
         + (f"  ·  ⚠ research truncated at cap" if report.get("truncated") else "")],
        [ctx.get("summary", "")],
        [level_str] if level_str else [""],
    ]

    cal = ctx.get("econ_calendar") or []
    if cal:
        rows.append([
            "CALENDAR:  " + "   |   ".join(
                f"{c.get('datetime_et', '')} {c.get('event', '')}"
                + (f" (cons. {c['consensus']})" if c.get("consensus") else "")
                for c in cal[:6]
            )
        ])

    rows.append([""])
    header_row = len(rows) + 1
    rows.append(HEADERS)

    ideas = sorted(report.get("recommendations", []), key=lambda i: i.get("rank", 99))
    rows.extend(idea_row(i) for i in ideas)

    watch = report.get("watchlist") or []
    if watch:
        rows.extend([[""], ["WATCHLIST — not yet actionable"]])
        for w in watch:
            rows.append([
                "", w.get("instrument", ""), w.get("symbol", ""), "", "", "", "", "", "", "", "",
                "", "", "", "", "", w.get("trigger", ""), "", "", w.get("note", ""), "", "",
            ])

    notes = report.get("data_quality_notes")
    if notes:
        rows.extend([[""], [f"DATA QUALITY: {notes}"]])
    rows.extend([[""], [DISCLAIMER]])
    return rows, header_row


