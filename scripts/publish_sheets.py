def validate(report: dict) -> None:
    try:
        import jsonschema
    except ImportError:
        print("  note: jsonschema not installed, skipping validation", file=sys.stderr)
        return
    jsonschema.validate(report, json.loads(SCHEMA_PATH.read_text()))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("report", type=Path)
    ap.add_argument("--dry-run", action="store_true", help="grade and render, but do not touch the Sheet")
    ap.add_argument("--skip-performance", action="store_true")
    args = ap.parse_args(argv)

    report = json.loads(args.report.read_text())
    validate(report)
    report_date = date.fromisoformat(report["date"])

    ideas = sorted(report.get("recommendations", []), key=lambda i: i.get("rank", 99))
    sectors = {}
    if not args.dry_run:
        try:
            import exposure as _exposure
            sectors = _exposure.fetch_sectors(ideas)
        except Exception as exc:  # noqa: BLE001
            print(f"  note: sector lookup unavailable: {exc}", file=sys.stderr)
    today_values, header_row, style_spec = build_today_values(report, sectors)

    # Grade prior calls before appending today's, so a repeat idea does not
    # get graded against itself on the same run.
    positions = load_state()
    if not args.skip_performance:
        print(f"Grading {len([p for p in positions if p.get('status') == 'open'])} open positions...")
        positions = [grade_position(p, report_date) for p in positions]

    # Keyed on entry as well as date, so the same ticker recommended twice with
    # different levels stays two independently graded rows.
    def key(p: dict) -> tuple:
        return (p.get("opened"), p.get("symbol"), p.get("direction"), p.get("entry"))

    existing = {key(p) for p in positions}
    new = [p for p in positions_from_report(report) if key(p) not in existing]
    positions.extend(new)
    print(f"Added {len(new)} new positions; {len(positions)} tracked in total.")

    # Two passes: the block's height is independent of where the detail table
    # starts, so measure it, then regenerate with the real row references.
    PREAMBLE = 2          # title + scorecard
    BETWEEN = 3           # blank, "POSITION DETAIL", header row
    block, _ = cumulative_rows(positions, 1)
    detail_first_row = PREAMBLE + len(block) + BETWEEN + 1
    block, perf_formats = cumulative_rows(positions, detail_first_row)

    perf_values = [["PERFORMANCE TRACKER"], summarize(positions)]
    perf_values.extend(block)
    perf_values.extend([[""], ["POSITION DETAIL"], PERF_HEADERS])
    # 0-based sheet row where the block begins, for the formatting pass.
    block_start = PREAMBLE
    perf_values.extend(
        perf_row(p) for p in sorted(positions, key=lambda p: p.get("opened", ""), reverse=True)
    )

    if args.dry_run:
        print("\n--- DRY RUN: Today tab ---")
        for row in today_values[:header_row + len(ideas) + 2]:
            print("  " + " | ".join(str(c)[:28] for c in row))
        print("\n--- DRY RUN: Performance tab ---")
        for row in perf_values[:12]:
            print("  " + " | ".join(str(c)[:22] for c in row))
        save_state(positions)
        print(f"\nState written to {STATE_PATH.relative_to(REPO)}. Sheet not touched.")
        return 0

    # Persist before touching Sheets. Grading and capture are already done and do
    # not depend on the Sheet, so a Google outage should not also cost us the
    # position tracking — that would silently orphan a day of picks.
    save_state(positions)
    print(f"State saved to {STATE_PATH.relative_to(REPO)} ({len(positions)} positions).")

    spreadsheet, client_email = open_spreadsheet()
    print(f"Opened spreadsheet as {client_email}")

    write_tab(spreadsheet, "Today", today_values, header_row, style_spec)
    print("  wrote 'Today'")

    write_tab(spreadsheet, report["date"], today_values, header_row, style_spec)
    print(f"  wrote archive '{report['date']}'")

    # USER_ENTERED so the cumulative formulas evaluate rather than showing as
    # text. The detail rows below are plain values and unaffected.
    perf_ws = write_tab(spreadsheet, "Performance", perf_values, detail_first_row - 1,
                        value_input_option="USER_ENTERED")
    try:
        style_performance(perf_ws, perf_formats, block_start, detail_first_row, len(perf_values))
    except Exception as exc:  # noqa: BLE001 - numbers matter more than formats
        print(f"  warning: performance formatting failed: {exc}", file=sys.stderr)
    print(f"  wrote 'Performance' (detail starts at row {detail_first_row})")

    # Conviction 4+ ideas with tap-to-open Robinhood links. USER_ENTERED so the
    # HYPERLINK formulas render as links rather than literal text.
    try:
        import watchlist as _watchlist
        entries = _watchlist.collect(report_date)
        write_tab(spreadsheet, "Watchlist",
                  _watchlist.render_rows(entries, report_date), 5,
                  value_input_option="USER_ENTERED")
        print(f"  wrote 'Watchlist' ({len(entries)} conviction 4+ instruments)")
    except Exception as exc:  # noqa: BLE001 - never block the main publish
        print(f"  warning: watchlist tab failed: {exc}", file=sys.stderr)

    # Keep Today and Performance at the front, archives behind them.
    try:
        order = ["Today", "Watchlist", "Performance"]
        spreadsheet.reorder_worksheets(
            [spreadsheet.worksheet(t) for t in order]
            + [ws for ws in spreadsheet.worksheets() if ws.title not in order]
        )
    except Exception as exc:  # noqa: BLE001
        print(f"  warning: could not reorder tabs: {exc}", file=sys.stderr)

    print(f"Done. {len(ideas)} ideas published for {report['date']}.")
    return 0


