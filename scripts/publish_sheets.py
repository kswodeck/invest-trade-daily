def fmt_price(value: Any, unit: str = "usd") -> str:
    if value is None:
        return ""
    if unit == "cents":
        return f"{value:g}¢"
    if unit == "index_points":
        return f"{value:,.2f}"
    return f"${value:,.2f}" if value < 1000 else f"${value:,.0f}"


def fmt_zone(entry: dict, unit: str) -> str:
    lo, hi = entry.get("zone_low"), entry.get("zone_high")
    if lo is None or hi is None:
        return ""
    return f"{fmt_price(lo, unit)} – {fmt_price(hi, unit)}"


def direction_label(direction: str) -> str:
    return {
        "buy": "BUY", "sell": "SELL", "sell_short": "SHORT",
        "long": "LONG", "short": "SHORT", "yes": "YES", "no": "NO",
    }.get(direction, direction.upper())


def _short_asof(raw: Any) -> str:
    """`2026-08-17T09:41:00-04:00` -> `08-17 09:41`. Empty when unknown."""
    if not raw:
        return ""
    text = str(raw)
    try:
        stamp = datetime.fromisoformat(text.replace("Z", "+00:00"))
        return stamp.strftime("%m-%d %H:%M")
    except ValueError:
        return text[:16]


def _spread_label(idea: dict) -> str:
    spread = (idea.get("validation") or {}).get("spread_pct")
    return f"{spread:.2f}%" if isinstance(spread, (int, float)) else ""


